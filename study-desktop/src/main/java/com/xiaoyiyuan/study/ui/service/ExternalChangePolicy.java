package com.xiaoyiyuan.study.ui.service;

/**
 * 检测到「文件被本应用之外的某一方改过」时，这次保存该怎么办。
 *
 * <p>三个取值对应界面上用户能得到的三条出路，且<b>默认行为必须是最保守的那一条</b>：
 * 用户还没做选择之前，磁盘上现有的内容才是权威——我们手里这份只是「打开时的快照」，
 * 一旦写下去，对方刚写的内容就永久没了，而备份救不回「从未保存过的东西」。
 */
public enum ExternalChangePolicy {

    /**
     * 询问用户：不写一个字节，把「重新载入 / 覆盖」的选择交回界面。
     *
     * <p>这是默认姿态，也是唯一「什么都不赌」的选项。
     */
    ASK_USER,

    /**
     * 重新载入：接受磁盘那一份为新基线，同样不写一个字节。
     *
     * <p>语义上它等价于「用户选择放弃这次编辑」——所以本策略只重新读盘，
     * 内存里的编辑由调用方按返回结果自行丢弃。
     */
    RELOAD,

    /**
     * 强制覆盖：用户已经明确看过、并确认要覆盖磁盘上那一份之后才会传进来的取值。
     *
     * <p>这是<b>唯一</b>能在检测到外部改动时仍然落盘的策略。
     */
    FORCE_OVERWRITE
}
